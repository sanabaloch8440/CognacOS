use std::{collections::BTreeSet, env, fs, path::PathBuf};

fn inventory(path: &str) -> BTreeSet<String> {
    println!("cargo:rerun-if-changed={path}");
    fs::read_to_string(path).unwrap_or_else(|e| panic!("cannot read {path}: {e}"))
        .lines().map(str::trim).filter(|s| !s.is_empty() && !s.starts_with('#'))
        .map(|name| { assert!(name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'), "invalid export {name:?}"); name.to_owned() })
        .collect()
}
fn main() {
    println!("cargo:rerun-if-changed=src/lib.rs");
    println!("cargo:rerun-if-changed=exports/kernel32-x64.def");
    let names = inventory("exports/windows-11-x64-exports.txt");
    let def = fs::read_to_string("exports/kernel32-x64.def").expect("missing kernel32 .def");
    let mut declared = BTreeSet::new();
    for raw in def.lines() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with(';') || line == "EXPORTS" || line.starts_with("LIBRARY ") { continue; }
        let name = line.split_whitespace().next().unwrap();
        assert!(names.contains(name), "kernel32 .def export {name} absent from inventory");
        declared.insert(name.to_owned());
    }
    assert_eq!(names, declared, "kernel32 .def and export inventory differ");
    let manual = ["GetLastError", "SetLastError", "GetCurrentProcess", "GetCurrentThread"];
    let mut output = String::from("// Generated by build.rs from the committed kernel32 export inventory.\n");
    let mut count = 0;
    for name in &names {
        if manual.contains(&name.as_str()) { continue; }
        output.push_str(&format!("#[no_mangle]\npub extern \"system\" fn {name}() -> ULONG_PTR {{ 0 }}\n"));
        count += 1;
    }
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
    fs::write(out.join("kernel32_export_stubs.rs"), output).expect("write generated kernel32 stubs");
    println!("cargo:warning=generated {count} kernel32 placeholder exports using cognacos-nt-abi types");
}
