use std::{collections::BTreeSet, env, fs, path::PathBuf};

fn inventory(path: &str) -> BTreeSet<String> {
    println!("cargo:rerun-if-changed={path}");
    fs::read_to_string(path).unwrap_or_else(|e| panic!("cannot read {path}: {e}"))
        .lines().map(str::trim).filter(|s| !s.is_empty() && !s.starts_with('#'))
        .map(|name| { assert!(name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'), "invalid export {name:?}"); name.to_owned() })
        .collect()
}
fn main() {
    println!("cargo:rerun-if-changed=src/lib.rs");
    println!("cargo:rerun-if-changed=exports/shell32-x64.def");
    let names = inventory("exports/windows-11-x64-exports.txt");
    let def = fs::read_to_string("exports/shell32-x64.def").expect("missing shell32 .def");
    let mut declared = BTreeSet::new();
    for raw in def.lines() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with(';') || line == "EXPORTS" || line.starts_with("LIBRARY ") { continue; }
        let name = line.split_whitespace().next().unwrap();
        assert!(names.contains(name), "shell32 .def export {name} absent from inventory");
        declared.insert(name.to_owned());
    }
    assert_eq!(names, declared, "shell32 .def and export inventory differ");
    let hresult = ["SHCreateItemFromParsingName", "SHGetDesktopFolder", "SHGetFolderPathA", "SHGetFolderPathW", "SHGetKnownFolderPath", "SHParseDisplayName"];
    let mut output = String::from("// Generated by build.rs from the committed shell32 export inventory.\n");
    for name in &names {
        if hresult.contains(&name.as_str()) {
            output.push_str(&format!("#[no_mangle]\npub extern \"system\" fn {name}() -> NTSTATUS {{ HRESULT_E_NOTIMPL }}\n"));
        } else {
            output.push_str(&format!("#[no_mangle]\npub extern \"system\" fn {name}() -> ULONG_PTR {{ 0 }}\n"));
        }
    }
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
    fs::write(out.join("shell32_export_stubs.rs"), output).expect("write generated shell32 stubs");
    println!("cargo:warning=generated {} shell32 placeholder exports using cognacos-nt-abi types", names.len());
}
