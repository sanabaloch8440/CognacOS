#[inline]
fn map_status(status: ULONG) -> ULONG {
    // The source table is sorted by range start, so binary search keeps the
    // full Wine mapping inexpensive without requiring a heap allocation.
    let mut low = 0usize;
    let mut high = STATUS_RANGES.len();
    while low < high {
        let mid = low + (high - low) / 2;
        let (start, end, offset) = STATUS_RANGES[mid];
        if status < start {
            high = mid;
        } else if status > end {
            low = mid + 1;
        } else {
            let index = (status - start) as usize + offset;
            return ERROR_MAP.get(index).copied().unwrap_or(ERROR_MR_MID_NOT_FOUND);
        }
    }
    ERROR_MR_MID_NOT_FOUND
}

/// Converts an NTSTATUS to a Win32 error without reading or updating the TEB.
#[no_mangle]
pub extern "system" fn RtlNtStatusToDosErrorNoTeb(status: NTSTATUS) -> ULONG {
    let mut status = status as ULONG;

    if status == 0 || (status & 0x2000_0000) != 0 {
        return status;
    }

    // NTSTATUS values with the 0xd severity/customer pattern alias 0xc.
    if status & 0xf000_0000 == 0xd000_0000 {
        status &= !0x1000_0000;
    }

    let high_word = status >> 16;
    if high_word == 0xc001 || high_word == 0x8007 || high_word == 0xc007 {
        return status & 0xffff;
    }

    map_status(status)
}

/// Converts an NTSTATUS to a Win32 error and records LastStatusValue.
#[no_mangle]
pub unsafe extern "system" fn RtlNtStatusToDosError(status: NTSTATUS) -> ULONG {
    // SAFETY: Native startup must install a writable TEB at the current GS base.
    unsafe {
        core::arch::asm!(
            "mov gs:[0x1250], {status:e}",
            status = in(reg) status,
            options(nostack, preserves_flags)
        );
    }
    RtlNtStatusToDosErrorNoTeb(status)
}

/// Returns the current TEB LastStatusValue.
#[no_mangle]
pub unsafe extern "system" fn RtlGetLastNtStatus() -> NTSTATUS {
    let status: NTSTATUS;
    // SAFETY: Requires CognacOS's native x64 TEB to be installed at GS.
    unsafe {
        core::arch::asm!(
            "mov {status:e}, gs:[0x1250]",
            status = out(reg) status,
            options(nostack, preserves_flags, readonly)
        );
    }
    status
}

